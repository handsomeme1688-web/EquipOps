package com.zoee.equipops.common.annotation;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;
/**
 * Java 注解有三种生命周期：
 *
 * ┌──────────┬──────────────────────┬────────────────────────────┐
 * │ Retentio │    存活到什么时候    │            用途            │
 * │    n     │                      │                            │
 * ├──────────┼──────────────────────┼────────────────────────────┤
 * │ SOURCE   │ 编译完就丢掉         │ @Override、@SuppressWarnin │
 * │          │                      │ gs                         │
 * ├──────────┼──────────────────────┼────────────────────────────┤
 * │          │ 保留在 .class        │                            │
 * │ CLASS    │ 文件，但 JVM         │ Lombok 的 @Data            │
 * │          │ 加载时丢弃           │                            │
 * ├──────────┼──────────────────────┼────────────────────────────┤
 * │ RUNTIME  │ JVM 运行时还能通过反 │ @OpLog、@RequestMapping    │
 * │          │ 射读到               │                            │
 * └──────────┴──────────────────────┴────────────────────────────┘
 */


/**
 * ┌──────────┬───────────────────────┬────────────────────────────┐
 * │          │  @Slf4j（应用日志）   │   @OpLog（操作审计日志）   │
 * ├──────────┼───────────────────────┼────────────────────────────┤
 * │ 写给谁看 │ 开发者、运维          │ 产品、审计、安全           │
 * ├──────────┼───────────────────────┼────────────────────────────┤
 * │ 存哪里   │ 日志文件（app.log）   │ 数据库表（operation_log）  │
 * ├──────────┼───────────────────────┼────────────────────────────┤
 * │ 内容     │ "第 3 行 SQL 执行耗时 │ "张三 于 14:30             │
 * │          │  200ms"               │ 创建了一条工单"            │
 * ├──────────┼───────────────────────┼────────────────────────────┤
 * │ 格式     │ 自由文本，排查问题用  │ 结构化字段，能查询统计     │
 * ├──────────┼───────────────────────┼────────────────────────────┤
 * │ 生命周期 │ 磁盘满了就删          │ 保留半年以上，合规要求     │
 * └──────────┴───────────────────────┴────────────────────────────┘
 */



// 注解定义
/** 贴在 Controller 方法上，AOP 自动记录操作日志 */
@Target(ElementType.METHOD) // 这个注解只能贴在方法上
@Retention(RetentionPolicy.RUNTIME) //注解信息保留到运行时
public @interface OpLog { // @interface 不是 class，它定义一个注解类型
    /** 资源类型，如 "order"、"device" */
    String resourceType();
    /** 动作，如 "create"、"update"、"delete" */
    String action();
    // 使用效果：@OpLog(resourceType = "order", action = "create")
}
